/** Rotation je Wort beim Mischen (RFC 2268, Kap. 3.1 und 4.1) */
const SHIFT = [1, 2, 3, 5] as const;

/** Schlüsselerweiterung (RFC 2268, Kap. 2): T Bytes Schlüssel, T1 Bit wirksame Länge, ergibt K[0..63] */
function expandKey(key: Uint8Array, effectiveBits: number): Uint16Array {
  if (key.length < 1 || key.length > 128 || effectiveBits < 1 || effectiveBits > 1024) throw new Error("RC2: ungültiger Schlüssel");
  const l = new Uint8Array(128);
  l.set(key);
  const t = key.length;
  const t8 = Math.ceil(effectiveBits / 8);
  const tm = 255 % 2 ** (8 + effectiveBits - 8 * t8);
  for (let i = t; i < 128; i++) l[i] = PITABLE[(l[i - 1]! + l[i - t]!) & 255]!;
  l[128 - t8] = PITABLE[l[128 - t8]! & tm]!;
  for (let i = 127 - t8; i >= 0; i--) l[i] = PITABLE[l[i + 1]! ^ l[i + t8]!]!;
  const k = new Uint16Array(64);
  for (let i = 0; i < 64; i++) k[i] = l[2 * i]! + 256 * l[2 * i + 1]!;
  return k;
}

/** Ein Block von 8 Bytes (RFC 2268, Kap. 4.5); die Wörter stehen mit dem niederwertigen Byte zuerst */
function decryptBlock(k: Uint16Array, block: Uint8Array): Uint8Array {
  const r = [0, 1, 2, 3].map((i) => block[2 * i]! | (block[2 * i + 1]! << 8));
  let j = 63;
  const rMixingRound = () => {
    for (let i = 3; i >= 0; i--) {
      const s = SHIFT[i]!;
      const x = ((r[i]! >>> s) | (r[i]! << (16 - s))) & 0xffff;
      const [prev1, prev2, prev3] = [r[(i + 3) % 4]!, r[(i + 2) % 4]!, r[(i + 1) % 4]!];
      r[i] = (x - k[j]! - (prev1 & prev2) - (~prev1 & prev3)) & 0xffff;
      j--;
    }
  };
  const rMashingRound = () => {
    for (let i = 3; i >= 0; i--) r[i] = (r[i]! - k[r[(i + 3) % 4]! & 63]!) & 0xffff;
  };
  for (const round of [5, -1, 6, -1, 5]) {
    if (round < 0) rMashingRound();
    else for (let n = 0; n < round; n++) rMixingRound();
  }
  return Uint8Array.from(r.flatMap((word) => [word & 0xff, word >>> 8]));
}

/** Einen Block entschlüsseln; für die Testvektoren aus RFC 2268, Kap. 5 */
export function rc2DecryptBlock(key: Uint8Array, effectiveBits: number, block: Uint8Array): Uint8Array {
  return decryptBlock(expandKey(key, effectiveBits), block);
}

/** RC2 im CBC-Modus entschlüsseln und das Padding nach PKCS #7 entfernen; null, wenn Länge oder Padding nicht stimmen */
export function rc2CbcDecrypt(key: Uint8Array, effectiveBits: number, iv: Uint8Array, data: Uint8Array): Uint8Array | null {
  if (iv.length !== 8 || data.length === 0 || data.length % 8 !== 0) return null;
  const k = expandKey(key, effectiveBits);
  const out = new Uint8Array(data.length);
  let previous = iv;
  for (let offset = 0; offset < data.length; offset += 8) {
    const block = data.subarray(offset, offset + 8);
    const plain = decryptBlock(k, block);
    for (let b = 0; b < 8; b++) out[offset + b] = plain[b]! ^ previous[b]!;
    previous = block;
  }
  const pad = out[out.length - 1]!;
  if (pad < 1 || pad > 8 || out.subarray(out.length - pad).some((b) => b !== pad)) return null;
  return out.subarray(0, out.length - pad);
}
